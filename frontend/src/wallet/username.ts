/**
 * The name a wallet wears until somebody chooses one.
 *
 * An address is 42 characters of hex and that is not a name, and
 * `hacker-58a57e` — the first six of it with a word in front — is the same hex
 * with the same problem. So an account that has not chosen a name gets
 * `AdjectiveNoun####`, derived from the address and from nothing else:
 *
 * ```text
 * hash = keccak256(utf8(lowercase(address)))   // the "0x" is included
 * adj  = uint16(hash[0..2]) % ADJECTIVES.length
 * noun = uint16(hash[2..4]) % NOUNS.length
 * num  = uint16(hash[4..6]) % 10000            // zero-padded to four
 * ```
 *
 * This exists **twice on purpose** — here and in `backend/core/src/username.rs`
 * — because each side needs it at a different moment. The server needs it to
 * name a row nobody seeded; the login screen needs it to show you the name
 * before you have an account to ask about. Both carry the same word lists in
 * the same order and the same four test vectors, and the vectors are what stop
 * the two drifting: the login box would otherwise promise a name the server
 * then disagrees with.
 *
 * The lists are `PocketSkynet-invites`'s, so a player carries one name between
 * the projects. **Order is protocol** — a word inserted anywhere but the end
 * renames every account whose index falls after it, and the lengths are the
 * modulus rather than a fact about the arrays.
 */
