/**
 * The name this address is known by when nobody has chosen one.
 *
 * Hashes the **address**, never the phrase: the same wallet reached by
 * recovery phrase, by private key, or at a different account index is one
 * account and has to arrive at one name.
 */
export function deterministicUsername(address: string): string {
  const digest = keccak_256(new TextEncoder().encode(address.toLowerCase()));
  const at = (i: number) => (digest[i] << 8) | digest[i + 1];
  const adjective = ADJECTIVES[at(0) % ADJECTIVES.length];
  const noun = NOUNS[at(2) % NOUNS.length];
  const number = String(at(4) % 10000).padStart(4, "0");
  return `${adjective}${noun}${number}`;
}
