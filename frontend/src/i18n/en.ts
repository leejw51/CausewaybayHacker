/**
 * English — the source.
 *
 * Every other catalogue in this folder is translated from this one and is
 * checked against it key for key by `tests/i18n.test.ts`. Add a key here first
 * and the test will name the five files that are now short of it.
 *
 * Conventions, because six languages amplify a sloppy one:
 *
 *   - **Keys are `screen.thing`**, in the order the screen draws them. A key is
 *     never reused across screens even when the English happens to match: RESET
 *     on the quest bench and CLEAR on the search box are the same four letters
 *     in English and three different words in Czech.
 *   - **`{name}` for anything substituted.** Never string concatenation at the
 *     call site, because word order is the first thing that moves.
 *   - **No sentence is assembled from fragments.** A phrase built out of "the",
 *     a noun and a verb in three keys is a phrase that cannot be translated.
 *   - **Counted things use `.one` / `.few` / `.other`** and go through `tn()`.
 *     Czech needs all three; Korean, Cantonese, Chinese and Japanese need one.
 *   - **ALL CAPS in a value is a style, not emphasis.** The chrome font has no
 *     lower case worth looking at, so Latin chrome labels are written upper
 *     case here and the CJK catalogues simply do not have a case to apply.
 */
