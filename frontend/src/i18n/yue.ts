/**
 * 廣東話 — Cantonese, written colloquially, in traditional characters.
 *
 * ## The fork, named on purpose
 *
 * Written Cantonese has two registers and they are not interchangeable:
 * colloquial written Cantonese (嘅／咗／唔／係／喺／睇／撳／而家／冇) and Standard
 * Written Chinese set in traditional characters. Most software in Hong Kong
 * ships the second — but then it differs from `zh.ts` only in glyph shape, and
 * a player would rightly ask why the game offers two of the same language.
 *
 * This file is the **first**: colloquial, because the game is set on Percival
 * Street and its narrator is somebody from the neighbourhood. `zh.ts` is
 * standard written Chinese and reads as a tool. The two are genuinely
 * different texts, not one text converted.
 *
 * The one place the colloquial register deliberately stops is the jargon.
 * Hong Kong developers say 提交, 編譯, 格式化 and 剪貼簿 in Cantonese speech —
 * there is no colloquial Cantonese word for "compile" and inventing one would
 * be worse than borrowing the standard term. So the connective prose is
 * Cantonese and the technical nouns are the ones people actually use.
 *
 * Terminology fixed once:
 *
 *   街／條街 street — a quest node.
 *   領地     land — RUST / GO. Not 大陸, which in Hong Kong means the mainland.
 *   任務     the job / brief.
 *   提交 SUBMIT ／ 執行 RUN ／ 格式化 FORMAT ／ 編譯 compile ／ 提示 hint.
 *   通關     cleared.
 *   助記詞   seed phrase.
 */
