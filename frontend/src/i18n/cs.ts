/**
 * Čeština — Czech.
 *
 * The one language of the six that needs **no new font**: Press Start 2P and
 * VT323 both carry the whole Czech alphabet, upper case and lower, every
 * diacritic — checked against their `cmap` tables rather than assumed, because
 * `Ě`, `Ř` and `Ů` are exactly the characters a Latin pixel font leaves out.
 *
 * It is also the language that makes the layout work hardest. Czech words are
 * longer than their English counterparts almost everywhere ("ODESLAT" for
 * SUBMIT, "SPUSTIT" for RUN, "FORMÁTOVAT" for FORMAT), so every button row in
 * this game is measured rather than reserved. Where a button is genuinely too
 * tight the short form is used and the long one lives in the footer hint.
 *
 * Terminology fixed once:
 *
 *   ulice     street — a quest node.
 *   kraj      land — RUST / GO.
 *   zadání    the job / brief.
 *   ODESLAT SUBMIT ／ SPUSTIT RUN ／ FORMÁTOVAT FORMAT ／ kompilace compile.
 *   splněno   cleared — "hotovo" is finished, "splněno" is passed, and the
 *             street is a task you pass.
 *   seed fráze  seed phrase. Czech wallet UIs mostly keep the English term;
 *             "seed fráze" is the half-borrowed form people actually write.
 *
 * Plurals go through `tn()` with three forms: 1 / 2–4 / 5 and up.
 */
